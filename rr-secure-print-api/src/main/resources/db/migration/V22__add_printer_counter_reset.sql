ALTER TABLE printers ADD COLUMN IF NOT EXISTS counter_offset_pages BIGINT DEFAULT 0;
ALTER TABLE printers ADD COLUMN IF NOT EXISTS counter_reset_at TIMESTAMP WITH TIME ZONE;

CREATE TABLE IF NOT EXISTS printer_counter_reset_logs (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    printer_code VARCHAR(64) NOT NULL,
    printer_name VARCHAR(160),
    department VARCHAR(64),
    previous_offset_pages BIGINT DEFAULT 0,
    actual_pages_at_reset BIGINT DEFAULT 0,
    delta_since_last_reset BIGINT DEFAULT 0,
    reset_by VARCHAR(64),
    reset_at TIMESTAMP WITH TIME ZONE NOT NULL
);
