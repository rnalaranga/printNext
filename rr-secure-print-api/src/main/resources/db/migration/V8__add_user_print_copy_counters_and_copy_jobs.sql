ALTER TABLE users ADD COLUMN IF NOT EXISTS print_count BIGINT DEFAULT 0 NOT NULL;
ALTER TABLE users ADD COLUMN IF NOT EXISTS copy_count BIGINT DEFAULT 0 NOT NULL;
ALTER TABLE users ADD COLUMN IF NOT EXISTS page_quota INT;

CREATE TABLE IF NOT EXISTS copy_jobs (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id BIGINT,
    printer_id BIGINT,
    username VARCHAR(64) NOT NULL,
    printer_name VARCHAR(128),
    printer_ip VARCHAR(64),
    pages INT NOT NULL DEFAULT 1,
    color_pages INT NOT NULL DEFAULT 0,
    mono_pages INT NOT NULL DEFAULT 0,
    printer_job_id VARCHAR(64),
    completed_at TIMESTAMP NOT NULL,
    created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT fk_copy_jobs_user FOREIGN KEY (user_id) REFERENCES users(id) ON DELETE SET NULL,
    CONSTRAINT fk_copy_jobs_printer FOREIGN KEY (printer_id) REFERENCES printers(id) ON DELETE SET NULL
);

CREATE UNIQUE INDEX IF NOT EXISTS idx_copy_jobs_printer_job_id ON copy_jobs(printer_ip, printer_job_id);
CREATE INDEX IF NOT EXISTS idx_copy_jobs_username ON copy_jobs(username);
CREATE INDEX IF NOT EXISTS idx_copy_jobs_completed_at ON copy_jobs(completed_at);
