-- Create scan_jobs audit table
CREATE TABLE IF NOT EXISTS scan_jobs (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id BIGINT,
    printer_id BIGINT,
    username VARCHAR(64) NOT NULL,
    printer_name VARCHAR(128),
    printer_ip VARCHAR(64),
    recipient_email VARCHAR(255) NOT NULL,
    subject VARCHAR(255),
    file_name VARCHAR(255),
    pages INT NOT NULL DEFAULT 1,
    color_mode VARCHAR(32) DEFAULT 'COLOR',
    resolution VARCHAR(32) DEFAULT '300DPI',
    file_format VARCHAR(32) DEFAULT 'PDF',
    duplex VARCHAR(32) DEFAULT 'SIMPLEX',
    status VARCHAR(32) NOT NULL DEFAULT 'SENT',
    delivery_message VARCHAR(512),
    completed_at TIMESTAMP NOT NULL,
    created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT fk_scan_jobs_user FOREIGN KEY (user_id) REFERENCES users(id) ON DELETE SET NULL,
    CONSTRAINT fk_scan_jobs_printer FOREIGN KEY (printer_id) REFERENCES printers(id) ON DELETE SET NULL
);

CREATE INDEX IF NOT EXISTS idx_scan_jobs_username ON scan_jobs(username);
CREATE INDEX IF NOT EXISTS idx_scan_jobs_recipient_email ON scan_jobs(recipient_email);
CREATE INDEX IF NOT EXISTS idx_scan_jobs_completed_at ON scan_jobs(completed_at);

